export const comics: Comic[] = records.map(
  ([slug, title, publisher, writer, artist, genre, year, price, description, featured]) => {
    const source = sources.find((s) => s.id === slug)
    if (!source?.image) throw new Error(`Missing verified cover: ${slug}`)
    return {
      slug,
      title,
      publisher,
      writer,
      artist,
      genre,
      year,
      price,
      description,
      featured,
      isNew: year === 2026,
      image: source.image,
      source: source.url,
    }
  },
)
export const money = (value: number) =>
  new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(value)
